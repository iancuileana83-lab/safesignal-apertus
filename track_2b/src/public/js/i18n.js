/** Translate a key; falls back to English, then to the key. {name} placeholders are filled from vars. */
export function tr(lang, key, vars = {}) {
  const d = DICT[lang] && DICT[lang][key] != null ? DICT[lang][key] : DICT.en[key];
  const s = d != null ? d : key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}

/** For 'label|hint' and 'label|question' entries. */
export function tr2(lang, key) {
  const [a, b] = tr(lang, key).split('|');
  return [a || '', b || ''];
}
